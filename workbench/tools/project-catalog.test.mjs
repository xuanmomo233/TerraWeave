import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {test} from 'node:test';

test('new projects preserve the original files and bind only their own save',async t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'terraweave-projects-'));
 const keys=['TERRAWEAVE_STATE','TERRAWEAVE_PRIMARY_STATE','TERRAWEAVE_WORLD','TERRAWEAVE_PRIMARY_WORLD'];
 const old=Object.fromEntries(keys.map(key=>[key,process.env[key]]));
 process.env.TERRAWEAVE_STATE=path.join(root,'original');
 for(const key of keys.slice(1))delete process.env[key];
 t.after(()=>{
  for(const key of keys){if(old[key]===undefined)delete process.env[key];else process.env[key]=old[key];}
  fs.rmSync(root,{recursive:true,force:true});
 });
 const {callTool,ROOT}=await import('./creative-workbench.mjs');
 const {projectFor}=await import('./project-catalog.mjs');
 const {writeVoidWorld}=await import('./void-world.mjs');
 const {worldSource}=await import('./world-source.mjs');
 const {relocateWorldSource,saveWorldSource}=await import('./world-source.mjs');
 const call=(name,args)=>callTool(name,args,{origin:'desktop'});
 await call('save_plan',{type:'marker',layer_id:'markers',name:'旧城门',points:[[40,-20]],notes:'保留'});
 const planning=fs.readFileSync(path.join(ROOT,'planning.json'),'utf8');
 const save=writeVoidWorld(root,'第二个存档',[0,64,0]);
 const one=await call('create_project',{type:'save',name:'第二工程',directory:save});
 const two=await call('create_project',{type:'void',name:'独立沙盘'});
 const three=await call('create_project',{type:'blank',name:'空白设计'});
 const projects=await call('list_projects');
 assert.equal(projects.length,4);
 assert.equal(projects.find(p=>p.current).id,'primary');
 assert.equal(projects.find(p=>p.id===one.id).directory,save);
 assert.equal(projects.find(p=>p.id===one.id).source_kind,'linked');
 assert.equal(projects.find(p=>p.id===two.id).source_kind,'project-world');
 assert.equal(projects.find(p=>p.id===two.id).world,'独立沙盘');
 assert.equal(projects.find(p=>p.id===three.id).world,null);
 assert.equal(worldSource(),null);
 const linkedRoot=projectFor(one.id).root;
 assert.deepEqual(fs.readdirSync(linkedRoot).sort(),['project.json','world-source.json']);
 const linkedConfig=fs.readFileSync(path.join(linkedRoot,'world-source.json'),'utf8');
 await call('rename_project',{id:one.id,name:'港口施工图'});
 await call('rename_project',{id:'primary',name:'原城市工程'});
 const renamed=await call('project_locations',{id:one.id});
 assert.equal(renamed.name,'港口施工图');
 assert.equal(renamed.project_directory,linkedRoot);
 assert.equal(renamed.directory,save);
 assert.equal(fs.readFileSync(path.join(linkedRoot,'world-source.json'),'utf8'),linkedConfig);
 assert.equal((await call('ui_snapshot')).project.name,'原城市工程');
 assert.equal(fs.readFileSync(path.join(ROOT,'planning.json'),'utf8'),planning);
 assert.ok([one,two,three].every(p=>!fs.existsSync(path.join(projectFor(p.id).root,'planning.json'))));
 await assert.rejects(call('create_project',{type:'save',name:'无效存档',directory:path.join(root,'missing')}),/ENOENT/);
 await assert.rejects(call('open_project',{id:'../../outside'}),/工程不存在/);
 assert.equal((await call('list_projects')).length,4);
 const parent=path.join(root,'backups');fs.mkdirSync(parent);
 const backup=await call('backup_project',{directory:parent});
 const restored=await call('restore_project_backup',{directory:backup.directory});
 assert.equal(fs.readFileSync(path.join(restored.project_directory,'planning.json'),'utf8'),planning);
 fs.appendFileSync(path.join(backup.directory,'planning.json'),' ');
 await assert.rejects(call('restore_project_backup',{directory:backup.directory}),/校验失败/);
 assert.equal((await call('list_projects')).length,5);

 const vanilla=writeVoidWorld(root,'无 UID 存档',[0,64,0]);
 fs.unlinkSync(path.join(vanilla,'uid.dat'));
 const source=saveWorldSource(vanilla);
 const moved=path.join(root,'迁移后的世界');
 fs.renameSync(vanilla,moved);
 assert.throws(()=>saveWorldSource(moved,source.world_uuid),/另一个世界/);
 assert.equal(relocateWorldSource(moved,source.world_uuid,false).world_uuid,source.world_uuid);
 assert.equal(worldSource().directory,moved);
 assert.equal(worldSource().world_uuid,source.world_uuid);
});
